#!/usr/bin/env python3
"""Writes a C++ source that maps packet header numbers to their names, from
the HEADER_ enumeration of src/packet.h.

  gen_packet_names.py src/packet.h > bf_packet_names.cpp
"""
import re, sys

text = open(sys.argv[1], 'rb').read().decode('latin-1')
names = {}
for name, value in re.findall(r'\bHEADER_([A-Z0-9_a-z]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,', text):
    names.setdefault(int(value, 0), name)

print('// Generated by port/tools/gen_packet_names.py from src/packet.h.')
print('#include "bf_trace.h"')
print('static const struct { int header; const char *name; } kNames[] = {')
for value in sorted(names):
    print(f'\t{{ 0x{value:04x}, "{names[value]}" }},')
print('};')
print('''
extern "C" const char *bf_packet_name(int header)
{
	int low = 0, high = (int)(sizeof(kNames) / sizeof(kNames[0])) - 1;
	while (low <= high) {
		int middle = (low + high) / 2;
		if (kNames[middle].header == header)
			return kNames[middle].name;
		if (kNames[middle].header < header)
			low = middle + 1;
		else
			high = middle - 1;
	}
	return 0;
}''')
