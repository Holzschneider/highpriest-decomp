class CMode {
public:
	CMode();
	virtual ~CMode();
	virtual int OnRun() { return FALSE; }
	virtual void OnInit(const char* modeName) {}
	virtual void OnExit() {}
	virtual void OnUpdate() {}
	virtual int SendMsg(int messageId, int val1 = 0, int val2 = 0, int val3 = 0);
	void Initialize();
	void PostQuitMsg();
	void ScreenShot();
	void SetCursorAction(int state);
	void RunFadeOut(int state);
	void DrawSprite(int x, int y, CActRes* act, CSprRes* spr, int actId, int motId, float zoom, float angle, unsigned long color);
	void DrawTexture(tagRECT* rect, int angle, float oow, unsigned long argb, CTexture* tex, UVRECT uvRect = UVRECT(0,0,1,1));
	void DrawBackGround2D(tagRECT* rect, int angle, float oow, unsigned long argb, CTexture* tex, UVRECT uvRect);
	void DrawMouseCursor();
	void DrawBattleMode();
	void MakeHelpBalloon(const char* helpMsg, int x, int y, unsigned long fntColor);
	void ProcessHelpBalloon();
	void ProcessFadeIn();
	void ProcessKeyBoard();
	int GetCursorAction();
	int GetCursorMotion();
	int GetSubMode();
	int GetLoopCond();
protected:
	virtual void OnChangeState(int state) {}
	void SetNextSubState(int state) { m_nextSubMode = state; }
	void SetSubState(int mode)
	{
		m_subMode = mode;
		m_subModeCnt = 0;
		m_nextSubMode = -1;
		OnChangeState(mode);
	}
protected:
	int m_subMode;
	int m_subModeCnt;
	int m_nextSubMode;
	int m_fadeInCount;
	int m_loopCond;
	int m_isConnected;
	UITransBalloonText* m_helpBalloon;
	unsigned long m_helpBalloonTick;
	unsigned long m_mouseAnimStartTick;
	int m_isMouseLockOn;
	int m_screenShotNow;
	vector2d m_mouseSnapDiff;
private:
	int m_cursorActNum;
	int m_cursorMotNum;
};

inline void CMode::PostQuitMsg()
{
	m_loopCond = 0;
}

