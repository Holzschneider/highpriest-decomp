// Budget filler: a steering marker. It stands in for source the original
// function held and whose content nothing shows.
//
// c2 sizes a function's inline budget by its own code before optimization,
// code the optimizer removes included (docs/compiler-notes.md, Inline
// budget), so such source decides which inline candidates the function
// expands.
//
// RAG_BUDGET_FILL(n) is a block holding one local and n dead stores to it:
//   { int rag_budget_fill; rag_budget_fill = 0; ... }
// The optimizer removes the stores and the local, so the filler leaves no
// machine code, no frame slot and no line record; it only enlarges the
// function before optimization. n is a decimal literal from 0 to 255.
//
// Codegen entropy (docs/compiler-notes.md, Codegen entropy): the local counts
// 1 for every function the unit compiles after the filler (stores, braces and
// constants count nothing), and the #include of this macro-only header counts
// 1 where it stands; it is included just before the first function that holds
// a filler, so functions before that keep their count.





