// RAG_BUDGET_FILL_VALUE() is the filler with its local tested:
//   { int rag_budget_fill = 0; if (rag_budget_fill) for (;;) { } }
// c2's first pass cannot remove the test (the local's value is not known to
// it and the endless loop is not dead code), so the store reaches the pass
// that numbers the function's distinct expressions and takes one late
// temporary (docs/compiler-notes.md); the passes after it fold the test, and
// the block leaves no machine code, frame slot or line record. It stands
// where a function's operand order needs one more distinct expression before
// the site and nothing shows what the original held there. Codegen entropy:
// the local, the if and the loop count 5 for every function the unit
// compiles after it.
//
//
#define RAG_BUDGET_FILL_VALUE() { int rag_budget_fill = 0; if (rag_budget_fill) for (;;) { } }
// RAG_BUDGET_FILL_LOOP() is the same marker in a lighter form:
//   { int rag_budget_fill = 0; do { } while (rag_budget_fill); }
// The loop's test of the local takes one late temporary (0x17f(local, #0)),
// as RAG_BUDGET_FILL_VALUE's does, at own size 16 against its 21. Unlike
// RAG_BUDGET_FILL_VALUE, whose 0x17e(#0, #0) is one expression however many
// times it stands, each RAG_BUDGET_FILL_LOOP tests its own local and so
// takes its own number (UIGuildInfoManageWnd::SendMsg: three of them
// move this->m_menuItems' address from late temporary 2 to 5). Codegen
// entropy: the local and the loop count 4 for every function the unit
// compiles after it.
#define RAG_BUDGET_FILL_LOOP() { int rag_budget_fill = 0; do { } while (rag_budget_fill); }
